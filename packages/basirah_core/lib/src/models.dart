/// Data models for the Basirah knowledge base and for the structured answers
/// that both the app and the API produce.
library;

/// How an answer is shaped. Mirrors the response-control rules of the
/// approved reference.
enum AnswerKind {
  /// A documented answer (levels A/B, or a constrained level-C answer).
  answer,

  /// A matter of recognised scholarly difference: state what is agreed upon,
  /// declare the difference, never pick a side.
  khilaf,

  /// A personal case or fatwa request (level D): general information only,
  /// then referral to a qualified person or body.
  refer,

  /// Not enough documented reference to answer with confidence.
  abstain,

  /// Not a question about Islam (restaurants, sport, another religion's
  /// doctrines for their own sake…): politely declined, never answered.
  offTopic;

  static AnswerKind parse(String? value) => AnswerKind.values.firstWhere(
    (k) => k.name == value,
    orElse: () => AnswerKind.abstain,
  );
}

/// Content levels (أ/ب/ج/د) from the reference pack.
enum ContentLevel {
  a('A', 'أ'),
  b('B', 'ب'),
  c('C', 'ج'),
  d('D', 'د');

  const ContentLevel(this.code, this.letterAr);

  final String code;
  final String letterAr;

  static ContentLevel parse(String? value) => ContentLevel.values.firstWhere(
    (l) => l.code == (value ?? '').trim().toUpperCase(),
    orElse: () => ContentLevel.b,
  );
}

/// Where an answer came from.
enum AnswerOrigin {
  /// Curated knowledge-base entry (human-authored, pending/after Sharia review).
  kb,

  /// Generated by the language model, grounded in the closed knowledge base.
  ai,

  /// Produced locally by the deterministic router (no model available).
  offline;

  static AnswerOrigin parse(String? value) => AnswerOrigin.values.firstWhere(
    (o) => o.name == value,
    orElse: () => AnswerOrigin.offline,
  );
}

enum EvidenceKind {
  quran,
  hadith;

  static EvidenceKind parse(String? value) =>
      value == 'hadith' ? EvidenceKind.hadith : EvidenceKind.quran;
}

/// A verbatim Quran verse or hadith from the closed evidence registry.
/// Answers may cite these by id only; they never quote free text.
class Evidence {
  const Evidence({
    required this.id,
    required this.kind,
    required this.text,
    this.surah,
    this.surahName,
    this.ayah,
    this.narrator,
    this.source,
    this.grade,
    this.search,
    this.tafsir,
    this.tafsirSource,
    this.tafsirUrl,
    this.note,
    this.translation,
    this.translationSource,
  });

  final String id;
  final EvidenceKind kind;

  /// The Arabic text, always shown as is.
  final String text;

  /// English meaning (Quran: King Fahd Complex's Hilali–Khan translation;
  /// hadith: team translation of the meaning, pending review).
  final String? translation;
  final String? translationSource;

  /// Verbatim tafsir excerpt shown under a verse (the explanation in
  /// موسوعة التفسير, الدرر السنية).
  final String? tafsir;
  final String? tafsirSource;

  /// Page with the full tafsir the model read (the passage on dorar.net/tafseer).
  final String? tafsirUrl;

  /// Model-written "why this verse is relevant" — labelled as generated.
  final String? note;

  // Quran
  final int? surah;
  final String? surahName;
  final String? ayah;

  // Hadith
  final String? narrator;
  final String? source;
  final String? grade;
  final String? search;

  bool get isQuran => kind == EvidenceKind.quran;

  /// Human-readable citation, e.g. «الممتحنة: 8» or «صحيح البخاري (2620)».
  String get reference =>
      isQuran ? '${surahName ?? ''}: ${ayah ?? ''}' : (source ?? '');

  /// Link to the approved platform where the text can be verified: for a
  /// verse, its own page (the first verse of a range) on the association's
  /// موسوعة المحتوى الإسلامي باللغات, with the Mushaf text and the approved
  /// translation.
  String get url => urlFor('ar');

  String urlFor(String lang) => isQuran
      ? 'https://islamenc.com/${lang == 'en' ? 'en' : 'ar'}/quran/${surah ?? 1}/${_firstAyah ?? 1}'
      : 'https://dorar.net/hadith/search?q=${Uri.encodeQueryComponent(search ?? text)}';

  int? get _firstAyah => int.tryParse((ayah ?? '').split(RegExp('[–-]')).first.trim());

  /// The surah in Dorar's tafsir encyclopedia (dorar.net/tafseer) — the
  /// tafsir platform named by the reference pack.
  String? get dorarTafsirUrl => isQuran && surah != null ? 'https://dorar.net/tafseer/$surah' : null;

  String get platformName => isQuran ? 'موسوعة المحتوى الإسلامي' : 'الدرر السنية';

  String platformNameFor(String lang) =>
      lang == 'en' ? (isQuran ? 'IslamEnc' : 'Dorar.net') : platformName;

  Evidence copyWith({
    String? text,
    String? surahName,
    String? narrator,
    String? source,
    String? grade,
    String? translation,
    String? translationSource,
    String? tafsir,
    String? tafsirSource,
    String? note,
  }) => Evidence(
    id: id,
    kind: kind,
    text: text ?? this.text,
    surah: surah,
    surahName: surahName ?? this.surahName,
    ayah: ayah,
    narrator: narrator ?? this.narrator,
    source: source ?? this.source,
    grade: grade ?? this.grade,
    search: search,
    tafsir: tafsir ?? this.tafsir,
    tafsirSource: tafsirSource ?? this.tafsirSource,
    tafsirUrl: tafsirUrl,
    note: note ?? this.note,
    translation: translation ?? this.translation,
    translationSource: translationSource ?? this.translationSource,
  );

  factory Evidence.fromJson(Map<String, dynamic> j) => Evidence(
    id: j['id'] as String,
    kind: EvidenceKind.parse(j['kind'] as String?),
    text: j['text'] as String,
    surah: j['surah'] as int?,
    surahName: j['surahName'] as String?,
    ayah: j['ayah']?.toString(),
    narrator: j['narrator'] as String?,
    source: j['source'] as String?,
    grade: j['grade'] as String?,
    search: j['search'] as String?,
    tafsir: j['tafsir'] as String?,
    tafsirSource: j['tafsirSource'] as String?,
    tafsirUrl: j['tafsirUrl'] as String?,
    note: j['note'] as String?,
    translation: j['translation'] as String?,
    translationSource: j['translationSource'] as String?,
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'kind': kind.name,
    'text': text,
    if (surah != null) 'surah': surah,
    if (surahName != null) 'surahName': surahName,
    if (ayah != null) 'ayah': ayah,
    if (narrator != null) 'narrator': narrator,
    if (source != null) 'source': source,
    if (grade != null) 'grade': grade,
    if (search != null) 'search': search,
    if (tafsir != null) 'tafsir': tafsir,
    if (tafsirSource != null) 'tafsirSource': tafsirSource,
    if (tafsirUrl != null) 'tafsirUrl': tafsirUrl,
    if (note != null) 'note': note,
    if (translation != null) 'translation': translation,
    if (translationSource != null) 'translationSource': translationSource,
  };

  /// Verse keys covered by a Quran item («60:8», or «53:3»,«53:4» for a range).
  List<String> get verseKeys {
    if (!isQuran || surah == null || ayah == null) return const [];
    final parts = ayah!.split(RegExp('[–-]')).map((s) => int.tryParse(s.trim())).toList();
    if (parts.isEmpty || parts.first == null) return const [];
    final from = parts.first!;
    final to = parts.length > 1 && parts[1] != null ? parts[1]! : from;
    return [for (var a = from; a <= to; a++) '$surah:$a'];
  }
}

