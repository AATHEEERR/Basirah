/// The reference pack's texts beyond the tables: the scope, the
/// association's statement (p. 8) and the notes on external platforms.
class PackTexts {
  const PackTexts({
    this.scope = const [],
    this.standardsIntro = '',
    this.associationName = '',
    this.associationAbout = '',
    this.associationFacts = const [],
    this.associationMcp = '',
    this.externalIntro = '',
    this.externalNote = '',
  });

  final List<String> scope;
  final String standardsIntro;
  final String associationName;
  final String associationAbout;
  final List<(String, String)> associationFacts;
  final String associationMcp;
  final String externalIntro;
  final String externalNote;

  factory PackTexts.fromJson(Map<String, dynamic> j) {
    final a = (j['association'] as Map?)?.cast<String, dynamic>() ?? const {};
    return PackTexts(
      scope: _strings(j['scopeText']),
      standardsIntro: (j['standardsIntro'] as String?) ?? '',
      associationName: (a['name'] as String?) ?? '',
      associationAbout: (a['about'] as String?) ?? '',
      associationFacts: [
        for (final f in (a['facts'] as List? ?? const []))
          ((f as Map)['item'] as String, f['text'] as String),
      ],
      associationMcp: (a['mcp'] as String?) ?? '',
      externalIntro: (j['externalIntro'] as String?) ?? '',
      externalNote: (j['externalNote'] as String?) ?? '',
    );
  }
}

/// The whole curated corpus. Loaded from `assets/kb/*.json` by the app and
/// from the same files by the API, so both always reason over one source.
class KnowledgeBase {
  KnowledgeBase({
    required this.version,
    required this.categories,
    required this.entries,
    required this.evidence,
    required this.glossary,
    required this.sources,
    required this.levels,
    required this.standards,
    this.platforms = const [],
    this.pack = const PackTexts(),
    this.lang = 'ar',
    Map<String, dynamic>? english,
  }) : _english = english,
       _entriesById = {for (final e in entries) e.id: e},
       _categoriesById = {for (final c in categories) c.id: c};

  /// Language of the texts: 'ar' (the master text) or 'en' (after [localized]).
  final String lang;

  /// Raw English overlay (`assets/kb/en.json`), if loaded.
  final Map<String, dynamic>? _english;

  bool get hasEnglish => _english != null;

  final String version;
  final List<Category> categories;
  final List<FaqEntry> entries;
  final Map<String, Evidence> evidence;
  final List<GlossaryTerm> glossary;
  final List<ApprovedSource> sources;
  final List<LevelPolicy> levels;
  final List<Standard> standards;

  /// The platforms of the reference pack (pp. 8–15), Arabic, verbatim.
  final List<ApprovedPlatform> platforms;
  final PackTexts pack;

  final Map<String, FaqEntry> _entriesById;
  final Map<String, Category> _categoriesById;

  FaqEntry? entry(String id) => _entriesById[id];
  Category? category(String id) => _categoriesById[id];

  List<FaqEntry> entriesIn(String categoryId) =>
      entries.where((e) => e.categoryId == categoryId).toList();

  List<FaqEntry> get popular => entries.where((e) => e.popular).toList();

  /// Resolves evidence ids, silently skipping anything not in the registry.
  List<Evidence> resolveEvidence(Iterable<String> ids) => [
    for (final id in ids)
      if (evidence[id] != null) evidence[id]!,
  ];

  LevelPolicy? policyFor(ContentLevel level) {
    for (final p in levels) {
      if (p.level == level) return p;
    }
    return null;
  }

  static const quranTranslationSource =
      'The Noble Quran — translation of the meanings by al-Hilali & Khan (King Fahd Complex)';
  static const hadithTranslationSource =
      'Translation of the meaning — Basirah team, pending review';

  /// The same knowledge base with English texts (Arabic Quran and hadith
  /// text are kept; their English meaning is added). Arabic questions stay
  /// searchable as variants, so either language finds the same entry.
  KnowledgeBase localized(String target) {
    final en = _english;
    if (target != 'en' || en == null || lang == 'en') return this;
    Map<String, dynamic> section(String name) =>
        (en[name] as Map?)?.cast<String, dynamic>() ?? const {};
    Map<String, dynamic>? item(String name, String id) =>
        (section(name)[id] as Map?)?.cast<String, dynamic>();
    String pick(Map<String, dynamic>? m, String key, String fallback) {
      final v = m?[key];
      return v is String && v.trim().isNotEmpty ? v : fallback;
    }

    List<T> list<T>(String name, List<T> base, T Function(T b, Map<String, dynamic> m) apply) {
      final rows = (en[name] as List?) ?? const [];
      return [
        for (var i = 0; i < base.length; i++)
          i < rows.length && rows[i] is Map ? apply(base[i], (rows[i] as Map).cast<String, dynamic>()) : base[i],
      ];
    }

    return KnowledgeBase(
      lang: 'en',
      english: en,
      version: version,
      platforms: platforms,
      pack: pack,
      categories: [
        for (final c in categories)
          () {
            final m = item('categories', c.id);
            return Category(
              id: c.id,
              title: pick(m, 'title', c.title),
              subtitle: pick(m, 'subtitle', c.subtitle),
              description: pick(m, 'description', c.description),
              hue: c.hue,
              star: c.star,
              icon: c.icon,
            );
          }(),
      ],
      entries: [
        for (final e in entries)
          () {
            final m = item('entries', e.id);
            final guidance = m?['guidance'] is List ? _strings(m!['guidance']) : e.guidance;
            return FaqEntry(
              id: e.id,
              categoryId: e.categoryId,
              question: pick(m, 'question', e.question),
              variants: [...e.variants, e.question],
              tags: e.tags,
              level: e.level,
              kind: e.kind,
              principle: pick(m, 'principle', e.principle),
              culture: pick(m, 'culture', e.culture),
              guidance: guidance,
              khilafAgreed: pick(m, 'khilafAgreed', e.khilafAgreed),
              khilafNote: pick(m, 'khilafNote', e.khilafNote),
              referReason: pick(m, 'referReason', e.referReason),
              referTo: pick(m, 'referTo', e.referTo),
              evidenceIds: e.evidenceIds,
              review: e.review,
              popular: e.popular,
            );
          }(),
      ],
      evidence: {
        for (final ev in evidence.values)
          ev.id: () {
            if (ev.isQuran) {
              final m = item('quran', ev.id);
              return ev.copyWith(
                text: m?['arabic'] as String?,
                surahName: pick(m, 'surahName', ev.surahName ?? ''),
                translation: m?['translation'] as String?,
                translationSource: m?['translation'] == null ? null : quranTranslationSource,
              );
            }
            final m = item('hadith', ev.id);
            return ev.copyWith(
              narrator: pick(m, 'narrator', ev.narrator ?? ''),
              source: pick(m, 'source', ev.source ?? ''),
              grade: pick(m, 'grade', ev.grade ?? ''),
              translation: m?['text'] as String?,
              translationSource: m?['text'] == null ? null : hadithTranslationSource,
            );
          }(),
      },
      glossary: [
        for (final g in glossary)
          GlossaryTerm(
            term: g.term,
            english: g.english,
            rule: pick({'rule': section('glossary')[g.term]}, 'rule', g.rule),
            keys: g.keys,
          ),
      ],
      sources: list(
        'sources',
        sources,
        (b, m) => ApprovedSource(
          field: pick(m, 'field', b.field),
          content: pick(m, 'content', b.content),
          rule: pick(m, 'rule', b.rule),
          links: b.links,
        ),
      ),
      levels: [
        for (final l in levels)
          () {
            final m = item('levels', l.level.code);
            return LevelPolicy(
              level: l.level,
              title: pick(m, 'title', l.title),
              scope: pick(m, 'scope', l.scope),
              handling: pick(m, 'handling', l.handling),
            );
          }(),
      ],
      standards: list(
        'standards',
        standards,
        (b, m) => Standard(
          title: pick(m, 'title', b.title),
          text: pick(m, 'text', b.text),
          applied: pick(m, 'applied', b.applied),
        ),
      ),
    );
  }

  /// Ids of items that have no English text yet (for tests and reviewers).
  List<String> missingEnglish() {
    final en = _english;
    if (en == null) return const ['<no en.json>'];
    bool has(String section, String id, List<String> keys) {
      final m = (en[section] as Map?)?[id];
      return m is Map && keys.every((k) => m[k] != null && m[k].toString().trim().isNotEmpty);
    }

    return [
      for (final c in categories)
        if (!has('categories', c.id, const ['title', 'subtitle', 'description'])) 'category:${c.id}',
      for (final e in entries)
        if (!has('entries', e.id, [
          'question',
          'guidance',
          if (e.principle.isNotEmpty) 'principle',
          if (e.culture.isNotEmpty) 'culture',
          if (e.khilafAgreed.isNotEmpty) 'khilafAgreed',
          if (e.khilafNote.isNotEmpty) 'khilafNote',
          if (e.referReason.isNotEmpty) 'referReason',
          if (e.referTo.isNotEmpty) 'referTo',
        ]))
          'entry:${e.id}',
      for (final ev in evidence.values)
        if (ev.isQuran && !has('quran', ev.id, const ['surahName', 'translation'])) 'quran:${ev.id}',
      for (final ev in evidence.values)
        if (!ev.isQuran && !has('hadith', ev.id, const ['narrator', 'text', 'source', 'grade'])) 'hadith:${ev.id}',
      for (final g in glossary)
        if (((en['glossary'] as Map?)?[g.term] ?? '').toString().trim().isEmpty) 'glossary:${g.term}',
      for (final l in levels)
        if (!has('levels', l.level.code, const ['title', 'scope', 'handling'])) 'level:${l.level.code}',
      if (((en['sources'] as List?) ?? const []).length != sources.length) 'sources',
      if (((en['standards'] as List?) ?? const []).length != standards.length) 'standards',
    ];
  }

  factory KnowledgeBase.fromJsonFiles({
    required Map<String, dynamic> categories,
    required Map<String, dynamic> faqs,
    required Map<String, dynamic> evidence,
    required Map<String, dynamic> reference,
    Map<String, dynamic>? english,
  }) {
    final ev = [
      for (final e in evidence['evidence'] as List)
        Evidence.fromJson(e as Map<String, dynamic>),
    ];
    return KnowledgeBase(
      english: english,
      version: (faqs['version'] as String?) ?? '0',
      categories: [
        for (final c in categories['categories'] as List)
          Category.fromJson(c as Map<String, dynamic>),
      ],
      entries: [
        for (final e in faqs['entries'] as List)
          FaqEntry.fromJson(e as Map<String, dynamic>),
      ],
      evidence: {for (final e in ev) e.id: e},
      glossary: [
        for (final g in reference['glossary'] as List)
          GlossaryTerm.fromJson(g as Map<String, dynamic>),
      ],
      sources: [
        for (final s in reference['sources'] as List)
          ApprovedSource.fromJson(s as Map<String, dynamic>),
      ],
      levels: [
        for (final l in reference['levels'] as List)
          LevelPolicy.fromJson(l as Map<String, dynamic>),
      ],
      standards: [
        for (final s in reference['standards'] as List)
          Standard.fromJson(s as Map<String, dynamic>),
      ],
      platforms: [
        for (final p in (reference['platforms'] as List? ?? const []))
          ApprovedPlatform.fromJson(p as Map<String, dynamic>),
      ],
      pack: PackTexts.fromJson(reference),
    );
  }
}

/// A structured answer, rendered by the app as colour-coded cards.
/// Produced from a curated entry, by the model, or by the offline router.
class BasirahAnswer {
  const BasirahAnswer({
    required this.question,
    required this.kind,
    required this.level,
    required this.origin,
    this.principle = '',
    this.culture = '',
    this.guidance = const [],
    this.khilafAgreed = '',
    this.khilafNote = '',
    this.referReason = '',
    this.referTo = '',
    this.abstainReason = '',
    this.evidence = const [],
    this.sourceNote = '',
    this.entryId,
    this.related = const [],
    this.review = 'pending',
    this.model,
    this.research = const [],
    this.guard = const [],
  });

  /// How the answer was researched, e.g. «بحث: …», «قراءة تفسير: الممتحنة ٨».
  final List<String> research;

  /// What the guard did to a live answer before it was shown (e.g. «dropped
  /// 60:8: cited without reading its tafsir»), for «إيصال بصيرة».
  final List<String> guard;

  final String question;
  final AnswerKind kind;
  final ContentLevel level;
  final AnswerOrigin origin;
  final String principle;
  final String culture;
  final List<String> guidance;
  final String khilafAgreed;
  final String khilafNote;
  final String referReason;
  final String referTo;
  final String abstainReason;
  final List<Evidence> evidence;

  /// Non-verse sources such as the approved glossary.
  final String sourceNote;

  /// The curated entry this answer comes from or is closest to.
  final String? entryId;

  /// Ids of related curated entries to suggest next.
  final List<String> related;
  final String review;
  final String? model;

  /// Stable key used for bookmarks.
  String get key => entryId != null && origin == AnswerOrigin.kb
      ? 'kb:$entryId'
      : 'q:${question.trim()}';

  factory BasirahAnswer.fromEntry(
    FaqEntry e,
    KnowledgeBase kb, {
    AnswerOrigin origin = AnswerOrigin.kb,
    String? question,
    List<String> related = const [],
    List<String> extraGuidance = const [],
  }) => BasirahAnswer(
    question: question ?? e.question,
    kind: e.kind,
    level: e.level,
    origin: origin,
    principle: e.principle,
    culture: e.culture,
    guidance: [...e.guidance, ...extraGuidance],
    khilafAgreed: e.khilafAgreed,
    khilafNote: e.khilafNote,
    referReason: e.referReason,
    referTo: e.referTo,
    // A referral (the question needs a specialist) cites nothing.
    evidence: e.kind == AnswerKind.refer ? const [] : kb.resolveEvidence(e.evidenceIds),
    entryId: e.id,
    related: related,
    review: e.review,
  );

  BasirahAnswer copyWith({
    String? question,
    List<String>? related,
    List<String>? guidance,
    List<String>? guard,
  }) => BasirahAnswer(
    question: question ?? this.question,
    kind: kind,
    level: level,
    origin: origin,
    principle: principle,
    culture: culture,
    guidance: guidance ?? this.guidance,
    khilafAgreed: khilafAgreed,
    khilafNote: khilafNote,
    referReason: referReason,
    referTo: referTo,
    abstainReason: abstainReason,
    evidence: evidence,
    sourceNote: sourceNote,
    entryId: entryId,
    related: related ?? this.related,
    review: review,
    model: model,
    research: research,
    guard: guard ?? this.guard,
  );

  factory BasirahAnswer.fromJson(Map<String, dynamic> j) => BasirahAnswer(
    question: (j['question'] as String?) ?? '',
    kind: AnswerKind.parse(j['kind'] as String?),
    level: ContentLevel.parse(j['level'] as String?),
    origin: AnswerOrigin.parse(j['origin'] as String?),
    principle: (j['principle'] as String?) ?? '',
    culture: (j['culture'] as String?) ?? '',
    guidance: _strings(j['guidance']),
    khilafAgreed: (j['khilafAgreed'] as String?) ?? '',
    khilafNote: (j['khilafNote'] as String?) ?? '',
    referReason: (j['referReason'] as String?) ?? '',
    referTo: (j['referTo'] as String?) ?? '',
    abstainReason: (j['abstainReason'] as String?) ?? '',
    evidence: [
      for (final e in (j['evidence'] as List? ?? const []))
        Evidence.fromJson(e as Map<String, dynamic>),
    ],
    sourceNote: (j['sourceNote'] as String?) ?? '',
    entryId: j['entryId'] as String?,
    related: _strings(j['related']),
    review: (j['review'] as String?) ?? 'pending',
    model: j['model'] as String?,
    research: _strings(j['research']),
    guard: _strings(j['guard']),
  );

  Map<String, dynamic> toJson() => {
    'question': question,
    'kind': kind.name,
    'level': level.code,
    'origin': origin.name,
    'principle': principle,
    'culture': culture,
    'guidance': guidance,
    'khilafAgreed': khilafAgreed,
    'khilafNote': khilafNote,
    'referReason': referReason,
    'referTo': referTo,
    'abstainReason': abstainReason,
    'evidence': [for (final e in evidence) e.toJson()],
    'sourceNote': sourceNote,
    'entryId': entryId,
    'related': related,
    'review': review,
    'model': model,
    'research': research,
    if (guard.isNotEmpty) 'guard': guard,
  };
}

List<String> _strings(Object? v) =>
    v is List ? [for (final x in v) x.toString()] : const [];
